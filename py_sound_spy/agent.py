"""
Класс игрового агента, управляемого пользователем.

Агент - это главный персонаж игры, которого игрок перемещает по лабиринту,
пытаясь добраться до финиша, избегая охранников.

Механика:
    - Управление: стрелки или WASD
    - Режимы движения: ходьба (тихо) и бег (быстро, но шумно)
    - При каждом движении создаётся звуковая волна
    - Металлические плитки усиливают шум в 2 раза
    - При достижении финиша (тайл 2) - победа
    - При столкновении с охранником - поимка
"""

import pygame

from py_sound_spy.constants import COLORS

# ============================================================
# Параметры агента
# ============================================================
# Размер спрайта агента в пикселях (квадрат).
AGENT_SIZE = 20

# Скорость движения в пикселях за кадр:
AGENT_SPEED_WALK = 3   # обычная ходьба
AGENT_SPEED_RUN = 6    # бег (быстрее в 2 раза)

# Минимальный интервал между созданием звуковых волн в миллисекундах.
# Предотвращает спам волнами при быстром движении.
WAVE_COOLDOWN_MS = 180


class Agent:
    """
    Агент, которого перемещает пользователь по лабиринту.

    Атрибуты:
        rect            - прямоугольник (pygame.Rect) с позицией и размером
        speed_walk      - скорость обычной ходьбы
        speed_run       - скорость бега
        running         - флаг режима бега (активируется зажатым Shift)
        last_wave_time  - время последней созданной волны (в миллисекундах)
        wave_cooldown   - минимальный интервал между волнами
    """

    def __init__(self, x, y):
        """
        Создаёт агента в указанной позиции.

        Параметры:
            x, y - начальные пиксельные координаты верхнего левого угла
        """
        self.rect = pygame.Rect(x, y, AGENT_SIZE, AGENT_SIZE)
        self.speed_walk = AGENT_SPEED_WALK
        self.speed_run = AGENT_SPEED_RUN
        self.running = False
        self.last_wave_time = 0
        self.wave_cooldown = WAVE_COOLDOWN_MS

    def move(self, dx, dy, walls):
        """
        Пытается сдвинуть агента в направлении (dx, dy).

        Логика:
            1. Определяет скорость в зависимости от режима (ходьба/бег)
            2. Создаёт пробный прямоугольник на новой позиции
            3. Проверяет коллизию со всеми стенами
            4. Если коллизии нет - обновляет позицию и возвращает True
            5. Если есть коллизия - возвращает False (движение заблокировано)

        Параметры:
            dx, dy  - направление движения (-1, 0 или 1 по осям X и Y)
            walls   - список стен для проверки коллизий

        Возвращает:
            True  - движение выполнено успешно
            False - движение заблокировано стеной
        """
        speed = self.speed_run if self.running else self.speed_walk
        new_rect = self.rect.move(dx * speed, dy * speed)
        for wall in walls:
            if new_rect.colliderect(wall):
                return False
        self.rect = new_rect
        return True

    def draw(self, surface):
        """
        Отрисовывает агента как синий прямоугольник со скруглёнными углами.

        Используется border_radius=4 для лёгкого визуального улучшения.
        """
        pygame.draw.rect(surface, COLORS["agent"], self.rect, border_radius=4)
