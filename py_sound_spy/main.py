"""
Точка входа в приложение Sound Spy.

При запуске этого файла:
1. Добавляется родительская директория в sys.path, чтобы пакет py_sound_spy
   был доступен для импорта независимо от текущей рабочей директории.
2. Импортируется и запускается основной игровой цикл из game.py.

Запуск:
    cd sound_spy/py_sound_spy/
    python3 main.py
"""

import sys
from pathlib import Path

# Добавляем родительскую директорию в путь поиска модулей Python.
# Это позволяет запускать main.py напрямую из папки py_sound_spy/,
# не нарушая структуру пакета.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

# Импортируем главную функцию игрового цикла из модуля game.
from py_sound_spy.game import main

# Стандартный Python-паттерн для скриптов: запускаем main() только при
# прямом выполнении файла, а не при импорте как модуля.
if __name__ == "__main__":
    main()
