"""
Класс звуковой волны, создаваемой при перемещении агента.

Звуковая волна - это круг, который расширяется от точки шага агента.
Охранники реагируют на волну, если она достигает их позиции.

Механика:
    - При каждом шаге агента создаётся новая волна
    - Волна расширяется со скоростью WAVE_SPEED
    - Максимальный радиус зависит от типа движения:
        * обычный шаг: WALK_RADIUS (20px)
        * бег: RUN_RADIUS (80px)
        * металлическая решётка: радиус удваивается
    - Прозрачность волны убывает с увеличением радиуса (эффект затухания)
    - Когда радиус достигает максимума, волна становится неактивной
"""

import pygame

from py_sound_spy.constants import COLORS

# Скорость расширения звуковой волны в пикселях за кадр.
WAVE_SPEED = 2.5


class SoundWave:
    """
    Круговая звуковая волна, создаваемая при шагах агента.

    Атрибуты:
        x, y       - координаты центра волны (эпицентра звука)
        radius     - текущий радиус волны
        max_radius - максимальный радиус до полного затухания
        speed      - скорость расширения в пикселях за кадр
        active     - флаг активности волны (False, когда она затухла)
    """

    def __init__(self, x, y, max_radius=200):
        """
        Создаёт новую звуковую волну.

        Параметры:
            x, y       - пиксельные координаты эпицентра
            max_radius - максимальный радиус волны (зависит от типа шага)
        """
        self.x = x
        self.y = y
        self.radius = 1
        self.max_radius = max_radius
        self.speed = WAVE_SPEED
        self.active = True

    def update(self):
        """
        Обновляет состояние волны: расширяет её.

        Волна остаётся активной, пока её радиус меньше максимального.
        Как только радиус достигает max_radius, волна деактивируется
        и удаляется из списка активных волн.
        """
        self.radius += self.speed
        if self.radius >= self.max_radius:
            self.active = False

    def draw(self, surface):
        """
        Отрисовывает волну как полупрозрачный красный контур.

        Прозрачность (alpha) рассчитывается обратно пропорционально
        отношению текущего радиуса к максимальному. Это создаёт
        эффект затухания волны по мере её расширения.

        Используется pygame.Surface с флагом SRCALPHA для поддержки
        полупрозрачности (alpha-канала).
        """
        if not self.active:
            return
        # Alpha убывает от 255 до 0 по мере расширения волны
        alpha = max(0, 255 - int((self.radius / self.max_radius) * 255))
        diameter = int(self.radius * 2)
        # Создаём поверхность размером с диаметр волны
        wave_surf = pygame.Surface((diameter, diameter), pygame.SRCALPHA)
        # Рисуем красный круг с текущей прозрачностью
        pygame.draw.circle(wave_surf, (255, 0, 0, alpha), (self.radius, self.radius), self.radius, 2)
        # Размещаем поверхность на игровом экране
        surface.blit(wave_surf, (self.x - self.radius, self.y - self.radius))
